-- The whole schema of a brig·id server.
--
-- One script: nothing was deployed that had to be kept, so the steps that led
-- here were folded into their result. From now on a change to the schema is a
-- new numbered script next to this one, and this one is never edited again.
--
-- BLOB columns marked "encrypted" hold AES-256-GCM ciphertext under a key
-- derived from the master key (per account, or per purpose for the server's
-- own secrets). TEXT dates are RFC 3339; INTEGER dates are Unix seconds.

-- -- Accounts -----------------------------------------------------------------

-- An account: a person's private way in. No profile, no e-mail, no password.
-- `username` is generated by the server and never typed; `username_index` is
-- a keyed hash of it, the only way to look an account up by name.
CREATE TABLE users (
    id             TEXT NOT NULL PRIMARY KEY,
    username       BLOB NOT NULL,          -- encrypted
    server         BLOB NOT NULL,          -- encrypted
    created_at     TEXT NOT NULL,
    username_index TEXT NOT NULL UNIQUE
);

-- The passkeys of an account. `data` is the credential as the WebAuthn
-- library keeps it (public key, counter); `label` is the name the person
-- gave it.
CREATE TABLE webauthn_credentials (
    id      TEXT NOT NULL PRIMARY KEY,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    data    BLOB NOT NULL,                 -- encrypted
    label   BLOB                           -- encrypted
);
-- Read by account at every sign-in.
CREATE INDEX idx_webauthn_credentials_user_id ON webauthn_credentials(user_id);

-- The recovery code of an account: one row per account that ever had one.
-- The secret itself is never stored, only a verifier. `recovery_index` is a
-- keyed hash of the code's public part, to find the account it names. Using
-- a code empties the three columns and records `used_at`.
CREATE TABLE account_recovery (
    user_id        TEXT NOT NULL PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    recovery_index TEXT UNIQUE,
    recovery_id    BLOB,                   -- encrypted
    verifier       BLOB,                   -- encrypted
    created_at     TEXT,
    used_at        TEXT
);

-- The sessions of accounts with this server. The browser holds a random
-- 256-bit token in an HttpOnly cookie; only its SHA3-256 hash is here. A
-- session ends at `idle_expires_at` (pushed back by each use, never past
-- `expires_at`) or at `expires_at`, fixed when the passkey opened it.
CREATE TABLE sessions (
    token_hash      TEXT    NOT NULL PRIMARY KEY,
    account_id      TEXT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at      INTEGER NOT NULL,
    idle_expires_at INTEGER NOT NULL,
    expires_at      INTEGER NOT NULL
);
CREATE INDEX idx_sessions_account_id ON sessions(account_id);
CREATE INDEX idx_sessions_expires_at ON sessions(expires_at);

-- -- Identities ---------------------------------------------------------------

-- An identity: what a person presents to an application. `name` and
-- `description` are for the person only; `logo` is a reference into the
-- interface's icon library (`icon:ph:<name>`), not a secret.
CREATE TABLE identities (
    id          TEXT NOT NULL PRIMARY KEY,
    account_id  TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        BLOB NOT NULL,             -- encrypted
    logo        TEXT NOT NULL,
    description BLOB,                      -- encrypted
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);
-- Listed by account on every account page.
CREATE INDEX idx_identities_account_id ON identities(account_id);

-- -- Applications -------------------------------------------------------------

-- The applications that may ask this server to sign people in. One that can
-- keep a secret has `secret_hash`, the SHA3-256 hash of a 256-bit random
-- secret; a public one has none. `redirect_uris` is a JSON array, compared
-- exactly.
CREATE TABLE clients (
    client_id     TEXT    NOT NULL PRIMARY KEY,
    name          TEXT    NOT NULL,
    redirect_uris TEXT    NOT NULL,
    secret_hash   TEXT,
    created_at    INTEGER NOT NULL
);

-- The identity an account last presented to an application, offered first at
-- the next sign-in. Each identity has its own identifier there.
CREATE TABLE client_identities (
    account_id  TEXT    NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_id   TEXT    NOT NULL REFERENCES clients(client_id) ON DELETE CASCADE,
    identity_id TEXT    NOT NULL REFERENCES identities(id) ON DELETE CASCADE,
    updated_at  INTEGER NOT NULL,
    PRIMARY KEY (account_id, client_id)
);

-- -- The server's own secrets -------------------------------------------------

-- The keys that sign ID tokens. The current one has `retired_at` NULL; a
-- retired one keeps verifying tokens until its grace period ends. `kid` is
-- public: it is in every token and in the published key set.
CREATE TABLE oidc_keys (
    kid        TEXT NOT NULL PRIMARY KEY,
    seed       BLOB NOT NULL,              -- encrypted (Ed25519 private seed)
    created_at TEXT NOT NULL,
    retired_at TEXT
);

-- Other secrets of the server. One row so far: `vsid`, from which the
-- identifier given to each application is derived.
CREATE TABLE server_secrets (
    name  TEXT NOT NULL PRIMARY KEY,
    value BLOB NOT NULL                    -- encrypted
);
