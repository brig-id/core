-- Identity logos name icons of the Phosphor set: `icon:ph:<name>`. The 45
-- references of the earlier library are converted once; any other value of
-- the old form becomes the plain person icon. `logo` is not encrypted.
UPDATE identities SET logo = CASE logo
    WHEN 'icon:solid:user' THEN 'icon:ph:user'
    WHEN 'icon:solid:user-tie' THEN 'icon:ph:user-circle-gear'
    WHEN 'icon:solid:user-astronaut' THEN 'icon:ph:rocket-launch'
    WHEN 'icon:solid:user-ninja' THEN 'icon:ph:sword'
    WHEN 'icon:solid:user-secret' THEN 'icon:ph:detective'
    WHEN 'icon:solid:masks-theater' THEN 'icon:ph:mask-happy'
    WHEN 'icon:solid:ghost' THEN 'icon:ph:ghost'
    WHEN 'icon:solid:people-roof' THEN 'icon:ph:house-line'
    WHEN 'icon:solid:children' THEN 'icon:ph:baby'
    WHEN 'icon:solid:people-group' THEN 'icon:ph:users-three'
    WHEN 'icon:solid:briefcase' THEN 'icon:ph:briefcase'
    WHEN 'icon:solid:building' THEN 'icon:ph:buildings'
    WHEN 'icon:solid:landmark' THEN 'icon:ph:bank'
    WHEN 'icon:solid:graduation-cap' THEN 'icon:ph:graduation-cap'
    WHEN 'icon:solid:book' THEN 'icon:ph:book-open'
    WHEN 'icon:solid:flask' THEN 'icon:ph:flask'
    WHEN 'icon:solid:code' THEN 'icon:ph:code'
    WHEN 'icon:solid:terminal' THEN 'icon:ph:terminal-window'
    WHEN 'icon:solid:laptop-code' THEN 'icon:ph:laptop'
    WHEN 'icon:solid:server' THEN 'icon:ph:hard-drives'
    WHEN 'icon:solid:palette' THEN 'icon:ph:palette'
    WHEN 'icon:solid:camera' THEN 'icon:ph:camera'
    WHEN 'icon:solid:music' THEN 'icon:ph:music-notes'
    WHEN 'icon:solid:gamepad' THEN 'icon:ph:game-controller'
    WHEN 'icon:solid:futbol' THEN 'icon:ph:soccer-ball'
    WHEN 'icon:solid:bicycle' THEN 'icon:ph:bicycle'
    WHEN 'icon:solid:mountain' THEN 'icon:ph:mountains'
    WHEN 'icon:solid:plane' THEN 'icon:ph:airplane-tilt'
    WHEN 'icon:solid:mug-hot' THEN 'icon:ph:coffee'
    WHEN 'icon:solid:chess-knight' THEN 'icon:ph:horse'
    WHEN 'icon:solid:house' THEN 'icon:ph:house'
    WHEN 'icon:solid:globe' THEN 'icon:ph:globe-hemisphere-west'
    WHEN 'icon:solid:cart-shopping' THEN 'icon:ph:shopping-cart'
    WHEN 'icon:solid:heart' THEN 'icon:ph:heart'
    WHEN 'icon:solid:star' THEN 'icon:ph:star'
    WHEN 'icon:solid:bolt' THEN 'icon:ph:lightning'
    WHEN 'icon:solid:leaf' THEN 'icon:ph:leaf'
    WHEN 'icon:solid:feather' THEN 'icon:ph:feather'
    WHEN 'icon:solid:gem' THEN 'icon:ph:diamond'
    WHEN 'icon:solid:shield-halved' THEN 'icon:ph:shield-check'
    WHEN 'icon:brands:github' THEN 'icon:ph:github-logo'
    WHEN 'icon:brands:gitlab' THEN 'icon:ph:gitlab-logo'
    WHEN 'icon:brands:discord' THEN 'icon:ph:discord-logo'
    WHEN 'icon:brands:mastodon' THEN 'icon:ph:mastodon-logo'
    WHEN 'icon:brands:linkedin' THEN 'icon:ph:linkedin-logo'
    ELSE 'icon:ph:user'
END
WHERE logo NOT LIKE 'icon:ph:%';
